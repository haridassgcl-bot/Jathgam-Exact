/**
 * Format coordinates nicely (e.g., 13.0827° N, 80.2707° E)
 */
function formatCoordinates(lat, lon) {
  const latStr = Math.abs(lat).toFixed(4) + (lat >= 0 ? "° N" : "° S");
  const lonStr = Math.abs(lon).toFixed(4) + (lon >= 0 ? "° E" : "° W");
  return `${latStr}, ${lonStr}`;
}

/**
 * Format timezone offset (e.g., UTC +5:30, UTC +8:00, UTC -5:00)
 */
function formatTimezone(tz) {
  const sign = tz >= 0 ? "+" : "-";
  const abs = Math.abs(tz);
  const hours = Math.floor(abs);
  const mins = Math.round((abs - hours) * 60);
  const minStr = mins < 10 ? "0" + mins : mins;
  return `UTC ${sign}${hours}:${minStr}`;
}

/**
 * Update place Geo badge and hidden inputs based on query string
 */
function updatePlaceGeoInfo(query) {
  const match = lookupPlace(query);
  const latInput = document.getElementById("inputLat");
  const lonInput = document.getElementById("inputLon");
  const tzInput = document.getElementById("inputTz");
  const geoCoordsText = document.getElementById("geoCoordsText");
  const geoTzBadge = document.getElementById("geoTzBadge");
  const placeBadge = document.getElementById("placeGeoBadge");

  if (match) {
    if (latInput) latInput.value = match.lat;
    if (lonInput) lonInput.value = match.lon;
    if (tzInput) tzInput.value = match.tz;
    if (geoCoordsText) geoCoordsText.textContent = formatCoordinates(match.lat, match.lon);
    if (geoTzBadge) geoTzBadge.textContent = formatTimezone(match.tz);
    if (placeBadge) placeBadge.style.display = "flex";

    const quickSelect = document.getElementById("quickDistrictSelect");
    if (quickSelect && quickSelect.options) {
      for (let i = 0; i < quickSelect.options.length; i++) {
        if (quickSelect.options[i].value === match.name) {
          quickSelect.selectedIndex = i;
          break;
        }
      }
    }

    return match;
  } else {
    const lat = parseFloat(latInput?.value) || 12.2253;
    const lon = parseFloat(lonInput?.value) || 79.0747;
    const tz = parseFloat(tzInput?.value) || 5.5;
    if (geoCoordsText) geoCoordsText.textContent = formatCoordinates(lat, lon);
    if (geoTzBadge) geoTzBadge.textContent = formatTimezone(tz);
    return null;
  }
}

