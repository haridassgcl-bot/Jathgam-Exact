/**
 * Look up a place by search query (bilingual fuzzy / exact match)
 */
function lookupPlace(query) {
  if (!query || typeof query !== "string") return null;
  const q = query.trim().toLowerCase();
  if (!q) return null;

  // 1. Exact match on name
  let found = GLOBAL_PLACES_DB.find(p => p.name.toLowerCase() === q);
  if (found) return found;

  // 2. Starts with query on city or country or name
  found = GLOBAL_PLACES_DB.find(p => p.city.toLowerCase().startsWith(q) || p.name.toLowerCase().startsWith(q));
  if (found) return found;

  // 3. Includes query in name
  found = GLOBAL_PLACES_DB.find(p => p.name.toLowerCase().includes(q));
  if (found) return found;

  // 4. Match country
  found = GLOBAL_PLACES_DB.find(p => p.country.toLowerCase().includes(q));
  if (found) return found;

  return null;
}

