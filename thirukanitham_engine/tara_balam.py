def _find_nakshatra_id(name: str) -> int:
    if not name:
        return 14
    clean = str(name).strip()
    for n in NAKSHATRAS_MASTER:
        if clean in n["ta"] or n["ta"] in clean or clean.lower() == n["en"].lower():
            return n["id"]
    return 14


