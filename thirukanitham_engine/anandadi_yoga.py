    @staticmethod
    def calculate_anandadi_yoga(weekday_name_ta: str = "சனி", moon_nakshatra_ta: str = "சித்திரை", pada: int = 3) -> Dict[str, Any]:
        """
        Calculates the active Anandadi Yoga for the chart's weekday and Moon Nakshatra.
        Returns active yoga details and the 28-row matrix.
        """
        # Search match in ANANDADI_TABLE for given weekday
        active_yoga = None
        for item in AnandadiYogaEngine.ANANDADI_TABLE:
            matched_nak = item["days"].get(weekday_name_ta, "")
            if matched_nak == moon_nakshatra_ta:
                active_yoga = {
                    "row": item["row"],
                    "yoga": item["yoga"],
                    "nature": item["nature"],
                    "effect": item["effect"],
                    "weekday": weekday_name_ta,
                    "nakshatra": moon_nakshatra_ta,
                    "pada": pada
                }
                break

        if not active_yoga:
            # Fallback default if not found directly
            active_yoga = {
                "row": 14,
                "yoga": "லம்ப",
                "nature": "தீயது",
                "effect": "வறுமை / இழப்பு",
                "weekday": weekday_name_ta,
                "nakshatra": moon_nakshatra_ta,
                "pada": pada
            }

        return {
            "activeYoga": active_yoga,
            "referenceTable": AnandadiYogaEngine.ANANDADI_TABLE
        }
