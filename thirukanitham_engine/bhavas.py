class BhavaEngine:
    """
    Computes 12 Bhavas, start, madhya, and end cusps under Thirukanitham,
    along with authentic classical predictive rules.
    """

    @staticmethod
    def calculate_bhavas(lagna_long: float, planets_map: dict) -> list:
        lagna_sign = int(lagna_long / 30.0)
        bhavas = []

        is_dhanusu = (lagna_sign == 8)

        for i in range(12):
            bhava_num = i + 1
            house_sign = (lagna_sign + i) % 12
            madhya_long = (lagna_long + (i * 30.0)) % 360.0
            arambha_long = (madhya_long - 15.0 + 360.0) % 360.0
            anthya_long = (madhya_long + 15.0) % 360.0

            lord_code = SIGN_LORDS[house_sign]
            meta = BHAVA_NAMES[i]

            # Find planets residing in this house
            occupants = []
            for code, p in planets_map.items():
                if code == "Asc":
                    continue
                if p["signId"] == house_sign:
                    occupants.append(p["nameTa"])

            # Retrieve rich classical predictions
            if is_dhanusu and bhava_num in DHANUSU_LAGNA_BHAVA_PREDICTIONS:
                points_ta = DHANUSU_LAGNA_BHAVA_PREDICTIONS[bhava_num]
            else:
                occ_txt = f"இங்கு அமர்ந்துள்ள {', '.join(occupants)} கிரகங்களின் தாக்கத்தால் விசேஷ பலன்கள் உண்டாகும்." if occupants else "சுப கிரகங்களின் பார்வைகள் மற்றும் சேர்க்கையால் பாவம் வலுவடைகிறது."
                points_ta = [
                    f"{SIGN_NAMES_TA[house_sign]} ராசியில் அமைந்துள்ள இபாவத்தின் அதிபதி {SIGN_NAMES_TA[house_sign]} நாதன் ஆவார்.",
                    occ_txt,
                    f"பாரம்பரிய ஜோதிட விதிப்படி {meta['ta']} தொடர்பான காரகத்துவங்கள் உரிய தசா-புக்தி காலங்களில் சிறப்பான நற்பலன்களைத் தரும்."
                ]

            pred_full = " ".join(points_ta)

            bhavas.append({
                "bhavaNumber": bhava_num,
                "titleTa": meta["ta"],
                "titleEn": meta["en"],
                "signId": house_sign,
                "signNameTa": SIGN_NAMES_TA[house_sign],
                "lordCode": lord_code,
                "madhyaLongitude": round(madhya_long, 2),
                "arambhaLongitude": round(arambha_long, 2),
                "anthyaLongitude": round(anthya_long, 2),
                "occupantsTa": ", ".join(occupants) if occupants else "கிரகங்கள் இல்லை (Empty)",
                "pointsTa": points_ta,
                "predTa": pred_full
            })

        return bhavas
